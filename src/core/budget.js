/**
 * 이 기기에 얼마를 쓸 것인가. 한 곳에서 답한다.
 *
 * ── 왜 기기를 나누는가 ──────────────────────────────────────────────────────
 * 이 아트 디렉션이 들여온 것은 대부분 **채우기 비용**이다: 블룸은 다섯 단계의
 * 분리 블러이고, 유리 재질은 환경맵을 샘플링하며, 그림자는 장면을 한 번 더 그린다.
 * 데스크톱에서는 셋 다 공짜에 가깝고 — 실측 120 fps, 월드 렌더 CPU 0.7 ms —
 * 폰에서는 셋 다 그렇지 않다.
 *
 * 두 갈래로만 나눈다. GPU 등급을 정밀하게 알아내는 방법은 없고, 알아낸다 해도
 * 세 갈래 이상은 시험할 수 없는 조합을 만든다. 나누는 기준도 성능 지표가 아니라
 * **포인터**다: 거친 포인터(손가락)와 마우스가 없다는 사실의 조합은 거의 정확히
 * "이것은 폰이나 태블릿이다" 이고, 그것이 이 프로젝트가 실제로 배포되는 두 가지다.
 *
 * ── 무엇을 깎는가 ───────────────────────────────────────────────────────────
 * 보이는 것부터가 아니라 **보이지 않는 것부터** 깎는다. 블룸 해상도를 절반으로
 * 내리면 블러 체인의 면적이 4분의 1이 되는데, 블룸은 정의상 저주파라 그 차이를
 * 볼 수 없다. 그림자 맵도 같은 성질이다 — 이 장면의 그림자는 평평한 판 위의
 * 부드러운 원반 몇 개다.
 *
 * 픽셀 비율은 여기서 정하지 않는다. `Viewport` 가 이미 2 로 묶고 있고, 그것은
 * 성능이 아니라 **글자**의 문제다 — 3배 화면에서 1로 내리면 UI 가 흐려진다.
 */

/**
 * 손가락으로 만지는 기기인가.
 *
 * `pointer: coarse` 만으로는 부족하다 — 터치스크린이 달린 노트북이 그것을 참으로
 * 만들면서 마우스도 갖고 있다. `any-hover: none` 과 함께 보아야 "정밀한 포인터가
 * **아무것도** 없다" 가 되고, 그게 폰과 태블릿이다.
 *
 * 미디어 쿼리를 못 쓰는 환경(테스트 러너 등)에서는 거짓 — 데스크톱 예산이 기본이다.
 */
function isHandheld() {
  try {
    return (
      globalThis.matchMedia?.('(pointer: coarse)').matches === true &&
      globalThis.matchMedia?.('(any-hover: none)').matches === true
    );
  } catch {
    return false;
  }
}

/**
 * 이 기기의 렌더 예산.
 *
 * 한 번 계산해 얼어붙인다. 폰이 도중에 데스크톱이 되지 않고, 매 프레임 미디어
 * 쿼리를 묻는 것은 낭비다. 화면 회전은 이 답을 바꾸지 않는다.
 *
 * @type {{handheld: boolean, bloomScale: number, shadowMapSize: number}}
 */
export const BUDGET = (() => {
  const handheld = isHandheld();
  return {
    handheld,
    /**
     * 블룸 블러 체인을 타겟의 몇 배 해상도로 돌릴 것인가.
     *
     * 0.5 는 면적의 4분의 1이다. 블룸은 저주파이므로 눈으로는 구별되지 않는다 —
     * 오히려 반 해상도에서 살짝 더 부드러워지는데, 그건 이 룩이 원하는 방향이다.
     * 데스크톱에서도 0.5 인 이유는, 같은 그림을 두 기기에서 다르게 만들 이유가
     * 없기 때문이다. 차이는 **비용**이지 결과가 아니어야 한다.
     */
    bloomScale: 0.5,
    /**
     * 그림자 맵 한 변.
     *
     * 2048 은 폰에서 16 MB 짜리 깊이 텍스처이고, 그만큼의 면적에 장면을 한 번 더
     * 그린다는 뜻이다. 이 장면의 그림자는 평평한 판 위의 부드러운 원반 몇 개라
     * 1024 에서 달라지는 것이 없다 — `sun.shadow.radius` 가 3 이라 PCF 가 그
     * 차이보다 넓게 번진다.
     */
    shadowMapSize: handheld ? 1024 : 2048,
  };
})();

/**
 * 기포가 떠오르는 법칙. **정의는 하나다.**
 *
 * ── 왜 별도의 모듈인가 ──────────────────────────────────────────────────────
 * 이 두 함수는 원래 `menu/Fizz.js` 안에 있었고, 승리 화면이 거기서 가져다 썼다.
 * 그쪽 주석이 그 사정을 이렇게 적어 두었다 — "법칙은 옮겨 다니고 그 클래스는
 * 아니다. 클래스는 병에 묶여 있다: `setProfile` 이 유리에 생성점을 놓고,
 * `envelopeAt` 이 각 줄기를 벽에 붙이고, `update` 가 병의 기울기만큼 빌보드를
 * 되돌린다. 승리 화면에는 그 어느 것도 건넬 병이 없다."
 *
 * 맞는 말이었지만 방향이 틀렸다. 승리 화면이 메뉴를 import 하는 것은 의존이
 * 거꾸로 선 것이고, 메뉴가 승리 화면을 import 하는 것도 마찬가지다. 어느 쪽도
 * 다른 쪽의 안으로 손을 뻗어서는 안 된다. 그래서 둘 다 여기를 본다.
 *
 * 중요한 규칙은 **정의가 하나라는 것**이지 그것이 어디 있느냐가 아니다. 사본이
 * 둘이 되어 따로 흘러가는 것이 부록 G 가 막으려던 실패다 — 한쪽에서 성장률의
 * 의미를 바꾸면 다른 쪽 기포는 조용히 다른 속도로 떠오르고, 두 화면을 나란히
 * 놓기 전에는 아무도 모른다.
 *
 * 여기 물리 상수를 더 넣지 마라. 이 파일은 **떠오르는 곡선** 하나에 관한 것이고,
 * 그 이상을 담기 시작하면 다시 무엇이든 들어가는 서랍이 된다.
 */

/**
 * a + g a^2 + g^2 a^3 / 3 — 반지름이 선형으로 자라는 기포의 상승 적분.
 *
 * 기포는 떠오르면서 커지고(압력이 낮아진다) 커지면서 빨라진다. 부력에 의한
 * 종단속도가 v = K r^2 이므로, r 이 시간에 대해 선형으로 자라면
 * r(a) = r0 (1 + g a) 이고 이동 거리는 그것의 제곱을 적분한 값이다:
 *
 *   y(a) = y0 + K r0^2 * P(a, g),   P(a, g) = a + g a^2 + g^2 a^3 / 3
 *
 * @param {number} a       기포의 나이 (초)
 * @param {number} growth  반지름 성장률 g (1/초)
 * @returns {number} 무차원 상승량. K r0^2 을 곱하면 거리가 된다
 */
export function risePolynomial(a, growth) {
  return a + growth * a * a + (growth * growth * a * a * a) / 3;
}

/**
 * 이 기포가 그 거리를 오르기까지 걸리는 시간.
 *
 * `risePolynomial(a) = distance` 에 대한 뉴턴법. 도함수가 정확히 (1 + g a)^2 —
 * 반지름 비의 제곱이고 그것이 곧 상승 속도다. 단조롭고 매끄러워서 어디서
 * 출발해도 서너 번에 수렴한다. 여섯 번 도는 것은 여유이지 필요가 아니다.
 *
 * @param {number} distance  올라야 할 무차원 거리
 * @param {number} growth    반지름 성장률 g (1/초)
 * @returns {number} 나이 (초). 아래로는 1e-4 에서 멈춘다 — 0 이면 도함수가
 *                   1 이 되어 수렴이 느려지고, 그보다 짧은 수명은 의미가 없다
 */
export function solveAge(distance, growth) {
  let a = distance;
  for (let n = 0; n < 6; n++) {
    const f = risePolynomial(a, growth) - distance;
    const d = (1 + growth * a) ** 2;
    a -= f / d;
    if (a < 1e-4) a = 1e-4;
  }
  return a;
}
